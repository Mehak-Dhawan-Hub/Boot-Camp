# Arithmetic Operators
a = 10
b = 5

print("Addition =", a + b)

# Relational Operator
print("a > b =", a > b)

# Logical Operator
print("a > 0 and b > 0 =", a > 0 and b > 0)

# If-elif-else ladder
marks = int(input("Enter your marks: "))

if marks >= 90:
    print("Grade A")
elif marks >= 50:
    print("Pass")
else:
    print("Fail")
